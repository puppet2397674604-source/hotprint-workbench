-- =============================================================================
-- HotPrint Workbench: Independent Cloud State Tables (`select_*`)
-- =============================================================================
-- Safety & Isolation Guarantees:
-- 1. Strictly isolated under the `select_` table prefix; NEVER touches upstream
--    `pp_records` or any `pp_*` tables.
-- 2. Fully idempotent (`CREATE TABLE IF NOT EXISTS` / `CREATE INDEX IF NOT EXISTS`);
--    safe to execute multiple times in Supabase SQL Editor.
-- =============================================================================

-- 1. Stage 02 Human Review Decisions (`manual_reviews`)
CREATE TABLE IF NOT EXISTS public.select_manual_reviews (
    domain INTEGER NOT NULL DEFAULT 1,
    asin TEXT NOT NULL,
    decision TEXT NOT NULL DEFAULT 'unreviewed',
    review_status TEXT NOT NULL DEFAULT 'unreviewed',
    reason_code TEXT,
    note TEXT,
    reason_note TEXT,
    operator_source TEXT NOT NULL DEFAULT 'workbench',
    basis_fingerprint TEXT NOT NULL DEFAULT '',
    last_request_id TEXT,
    reviewed_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY (domain, asin)
);

CREATE INDEX IF NOT EXISTS idx_select_manual_reviews_status
    ON public.select_manual_reviews (domain, review_status);

-- 2. DeepSeek Vision v2 Incremental Cache (`product_ai_cache`)
CREATE TABLE IF NOT EXISTS public.select_product_ai_cache (
    asin TEXT PRIMARY KEY,
    evidence_hash TEXT NOT NULL,
    model TEXT NOT NULL DEFAULT 'deepseek-flash',
    prompt_version TEXT NOT NULL DEFAULT 'v2',
    is_graphic_print BOOLEAN NOT NULL DEFAULT FALSE,
    pattern_type TEXT NOT NULL DEFAULT '',
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    filter_reason TEXT NOT NULL DEFAULT '',
    print_subject TEXT NOT NULL DEFAULT '',
    slogan_text TEXT NOT NULL DEFAULT '',
    visual_style TEXT NOT NULL DEFAULT '',
    theme_tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    season_tag TEXT NOT NULL DEFAULT '',
    motif TEXT NOT NULL DEFAULT '',
    transferability TEXT NOT NULL DEFAULT '',
    raw_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_select_product_ai_cache_filter
    ON public.select_product_ai_cache (is_graphic_print, confidence, pattern_type);

-- 3. Stage 05 Print Trend Directions (`print_directions`)
CREATE TABLE IF NOT EXISTS public.select_print_directions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    style_tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    target_audience TEXT NOT NULL DEFAULT '',
    feasibility_rating INTEGER NOT NULL DEFAULT 3 CHECK (feasibility_rating BETWEEN 1 AND 5),
    notes TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'shortlisted', 'archived')),
    shortlisted BOOLEAN NOT NULL DEFAULT FALSE,
    direction_type TEXT NOT NULL DEFAULT 'trend_cluster',
    source TEXT NOT NULL DEFAULT 'manual',
    variant_suggestions JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_select_print_directions_status
    ON public.select_print_directions (status, updated_at);

-- 4. Stage 05 Direction <-> ASIN Many-to-Many Links (`direction_asin_links`)
CREATE TABLE IF NOT EXISTS public.select_direction_asin_links (
    direction_id BIGINT NOT NULL REFERENCES public.select_print_directions(id) ON DELETE CASCADE,
    asin TEXT NOT NULL,
    added_at TEXT NOT NULL,
    PRIMARY KEY (direction_id, asin)
);

CREATE INDEX IF NOT EXISTS idx_select_direction_asin_links_asin
    ON public.select_direction_asin_links (asin);

-- 5. Stage 06 Shortlisted Direction Frozen Snapshots (`direction_frozen_snapshots`)
CREATE TABLE IF NOT EXISTS public.select_direction_frozen_snapshots (
    direction_id BIGINT NOT NULL REFERENCES public.select_print_directions(id) ON DELETE CASCADE,
    observed_date TEXT NOT NULL,
    direction_name TEXT NOT NULL DEFAULT '',
    direction_score DOUBLE PRECISION,
    season_tag TEXT NOT NULL DEFAULT 'evergreen',
    snapshot_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    frozen_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY (direction_id, observed_date)
);

CREATE INDEX IF NOT EXISTS idx_select_direction_frozen_snapshots_date
    ON public.select_direction_frozen_snapshots (observed_date);

-- 6. Stage 04 Scoring Weight Presets (`scoring_presets`)
CREATE TABLE IF NOT EXISTS public.select_scoring_presets (
    preset_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    weights_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    price_ranges_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

-- Ensure PostgREST API roles have table privileges and reload PostgREST schema cache
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE
    public.select_manual_reviews,
    public.select_product_ai_cache,
    public.select_print_directions,
    public.select_direction_asin_links,
    public.select_direction_frozen_snapshots,
    public.select_scoring_presets
TO anon, authenticated, service_role;

NOTIFY pgrst, 'reload schema';
